#!/usr/bin/env bash
# notify.sh — surface Claude Code hook events as desktop notifications.
#
# Wired in `.claude/settings.json` against: Notification, Stop, TaskCreated,
# TaskCompleted. Reads JSON from stdin per Claude Code hook protocol; the event
# name is in `hook_event_name` (older `event_type` / `type` keys are a fallback).
#
# Cross-platform: macOS uses osascript, Linux uses notify-send when available,
# Windows (Git Bash) shows a balloon tip via powershell.exe. Falls back to
# writing to /tmp/<team>-hooks.log on unknown events / unsupported OS.
# Uses jq when installed; otherwise a sed fallback reads top-level string keys.
#
# TaskCreated / TaskCompleted are also appended to .claude/agent-activity.log,
# which teammate-idle-gate.sh reads.
#
# Generated by agents-team `/team-gen`. The {{TEAM_NAME}} token is replaced
# at generation time; if you copied this manually, replace it yourself.

set -u

TEAM_NAME="{{TEAM_NAME}}"
LOG_FILE="/tmp/${TEAM_NAME,,}-hooks.log"
ACTIVITY_LOG="${CLAUDE_PROJECT_DIR:-.}/.claude/agent-activity.log"

INPUT=$(cat)

# json_get <key> [default] — top-level string value from $INPUT.
json_get() {
  local key="$1" default="${2:-}" value
  if command -v jq >/dev/null 2>&1; then
    value=$(printf '%s' "$INPUT" | jq -r --arg k "$key" '.[$k] // empty | tostring' 2>/dev/null)
  else
    value=$(printf '%s' "$INPUT" | tr -d '\n' \
      | sed -n "s/.*\"${key}\"[[:space:]]*:[[:space:]]*\"\([^\"]*\)\".*/\1/p")
  fi
  printf '%s' "${value:-$default}"
}

EVENT_TYPE=$(json_get hook_event_name)
[[ -z "$EVENT_TYPE" ]] && EVENT_TYPE=$(json_get event_type)
[[ -z "$EVENT_TYPE" ]] && EVENT_TYPE=$(json_get type unknown)

# log_activity <event> — one JSON line per task event for teammate-idle-gate.sh.
log_activity() {
  local event="$1" id teammate task
  id=$(json_get task_id)
  teammate=$(json_get teammate_name)
  task=$(json_get task_subject)
  [[ -z "$id" ]] && return 0
  mkdir -p "$(dirname "$ACTIVITY_LOG")" 2>/dev/null || return 0
  task=${task//\\/\\\\}; task=${task//\"/\\\"}
  printf '{"event":"%s","teammate":"%s","task":"%s","id":"%s"}\n' \
    "$event" "$teammate" "$task" "$id" >> "$ACTIVITY_LOG" 2>/dev/null || true
}

notify() {
  local title="$1"
  local body="$2"
  local sound="${3:-Glass}"

  case "$(uname -s)" in
    Darwin)
      osascript -e "display notification \"${body}\" with title \"${title}\" sound name \"${sound}\""
      ;;
    Linux)
      if command -v notify-send >/dev/null 2>&1; then
        notify-send "$title" "$body"
      else
        echo "[notify] $(date -u +%Y-%m-%dT%H:%M:%SZ) $title: $body" >> "$LOG_FILE"
      fi
      ;;
    MINGW*|MSYS*|CYGWIN*)
      echo "[notify] $(date -u +%Y-%m-%dT%H:%M:%SZ) $title: $body" >> "$LOG_FILE"
      if command -v powershell.exe >/dev/null 2>&1; then
        NOTIFY_TITLE="$title" NOTIFY_BODY="$body" powershell.exe -NoProfile -NonInteractive -Command '
          Add-Type -AssemblyName System.Windows.Forms, System.Drawing
          $n = New-Object System.Windows.Forms.NotifyIcon
          $n.Icon = [System.Drawing.SystemIcons]::Information
          $n.Visible = $true
          $n.ShowBalloonTip(5000, $env:NOTIFY_TITLE, $env:NOTIFY_BODY, "Info")
          Start-Sleep -Seconds 5
          $n.Dispose()' >/dev/null 2>&1 &
      fi
      ;;
    *)
      echo "[notify] $(date -u +%Y-%m-%dT%H:%M:%SZ) $title: $body" >> "$LOG_FILE"
      ;;
  esac
}

case "$EVENT_TYPE" in
  Notification)
    MESSAGE=$(json_get message "${TEAM_NAME} needs your attention")
    TITLE=$(json_get title "${TEAM_NAME}")
    notify "$TITLE" "$MESSAGE" "Glass"
    ;;
  Stop)
    SESSION=$(json_get session_id)
    # Stop fires when Claude finishes a turn, not when the session closes.
    body="Claude finished — waiting for you"
    [[ -n "$SESSION" ]] && body="Claude finished (session ${SESSION:0:8}) — waiting for you"
    notify "$TEAM_NAME" "$body" "Purr"
    ;;
  TaskCreated)
    log_activity TaskCreated
    ;;
  TaskCompleted)
    log_activity TaskCompleted
    TASK=$(json_get task_subject "$(json_get task_title Task)")
    AGENT=$(json_get teammate_name "$(json_get agent_type)")
    body="${TASK} completed"
    [[ -n "$AGENT" ]] && body="${TASK} — completed by ${AGENT}"
    notify "$TEAM_NAME" "$body" "Glass"
    ;;
  *)
    echo "[notify] $(date -u +%Y-%m-%dT%H:%M:%SZ) event=${EVENT_TYPE} data=${INPUT}" >> "$LOG_FILE"
    ;;
esac
